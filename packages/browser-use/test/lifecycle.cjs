const assert = require("node:assert/strict");
const { once } = require("node:events");

module.exports = async function lifecycle(host, window, base, baseChildren) {
  const id = "lifecycle";
  const bounds = { x: 400, y: 100, width: 600, height: 600 };
  const selectedPage = () => window.contentView.children.find((view) => view.getVisible() && view.webContents !== window.webContents).webContents;
  host.layout(id, bounds);
  await host.command(id, { action: "new", url: base });
  const firstId = host.state(id).selectedId;
  await host.command(id, { action: "new", url: `${base}/second` });
  const page = selectedPage();
  const destroyed = once(page, "destroyed");
  page.close();
  await destroyed;
  await host.command(id, { action: "select", tabId: firstId });
  assert.equal(host.state(id).tabs.length, 1, "destroyed pages leave the tab list");
  assert.equal(host.state(id).selectedId, firstId);
  assert.equal(window.contentView.children.length, baseChildren + 1);
  const remaining = selectedPage();
  const lastDestroyed = once(remaining, "destroyed", { signal: AbortSignal.timeout(5000) });
  await remaining.executeJavaScript("setTimeout(() => window.close(), 0); undefined");
  await lastDestroyed;
  assert.equal(host.state(id).selectedId, null, "closing the last page clears selection");
  assert.equal(host.state(id).tabs.length, 0);
  assert.equal(window.contentView.children.length, baseChildren);
  await host.command(id, { action: "new", url: base });
  const replacementId = host.state(id).selectedId;
  await host.command(id, { action: "new", url: `${base}/replacement` });
  await host.command(id, { action: "close", tabId: replacementId });
  assert.equal(host.state(id).tabs.length, 1, "closing a background tab leaves the selected page alone");
  await host.command(id, { action: "close", tabId: host.state(id).selectedId });
  assert.equal(host.state(id).tabs.length, 0);
  await host.command(id, { action: "new", url: base });
  const runningPage = selectedPage();
  const running = host.execute(id, "browser_evaluate", { expression: "window.waitingForClose=true; new Promise(() => {})" });
  const rejected = assert.rejects(running, /closed|destroyed|target/i);
  await runningPage.executeJavaScript("(async () => { while (!window.waitingForClose) await new Promise(resolve => setTimeout(resolve, 0)); })()");
  await host.command(id, { action: "close", tabId: host.state(id).selectedId });
  await rejected;
  await host.command(id, { action: "new", url: base });
  host.closeSession(id);
  assert.equal(window.contentView.children.length, baseChildren);
  host.layout("after-close", bounds);
  await host.command("after-close", { action: "new", url: base });
  host.closeSession("after-close");
};
